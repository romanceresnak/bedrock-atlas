"""Export the public, anonymized dataset for the map.

Input:  data/private/records.jsonl (from normalize.py)
Output: web/public/data/requests.json   allow-listed fields only
        web/public/data/regions.json    approximate points of all known regions
        web/public/data/meta.json       collection date, coverage, limitations

Identities are published as "<team>/session-N" (numbered by first appearance).
Principal ARNs, account id, prompts and responses are never exported.

Usage:  python scripts/export_public.py
"""
import json
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECORDS = ROOT / "data" / "private" / "records.jsonl"
OUT = ROOT / "web" / "public" / "data"

ALLOWED = [
    "request_id", "timestamp", "operation", "source_region", "model_id", "base_model",
    "inference_mode", "processing_region", "region_evidence", "region_sources",
    "team", "principal_type", "input_tokens", "output_tokens", "estimated_cost_usd",
    "cost_status", "price_effective_date", "client_latency_ms", "service_latency_ms",
    "workload", "phase", "item_id", "score",
]

LIMITATIONS = [
    "Controlled test workload generated by the author with synthetic, non-sensitive texts. Not production customer traffic.",
    "One AWS account, source regions eu-central-1 and us-east-1, Converse/ConverseStream API only.",
    "Estimated inference cost covers on-demand text input/output tokens without caching. It is not a billing reconciliation.",
    "Price is taken from the source region of the call, never from the processing region.",
    "Region points are approximate metro areas. Lines are logical source-to-processing relationships, not network paths.",
    "'direct' means a call without an inference profile; processing region equals the source region by AWS on-demand behavior.",
    "Phase 'spike' is a controlled scenario: the research team requested detailed analyses with the same number of requests.",
]


def main():
    records = [json.loads(l) for l in RECORDS.read_text().splitlines()]
    region_points = json.loads((ROOT / "config" / "regions.json").read_text())["regions"]

    sessions = {}
    public = []
    for r in records:
        key = (r["team"], r["principal_arn"])
        if key not in sessions:
            n = sum(1 for t, _ in sessions if t == r["team"]) + 1
            sessions[key] = f"{r['team']}/session-{n}"
        public.append({"identity": sessions[key], **{k: r[k] for k in ALLOWED}})

    used = {r["source_region"] for r in public} | {r["processing_region"] for r in public if r["processing_region"]}
    missing = used - region_points.keys()
    if missing:
        raise SystemExit(f"Add coordinates to config/regions.json for: {sorted(missing)}")

    meta = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "collection_start": public[0]["timestamp"],
        "collection_end": public[-1]["timestamp"],
        "records": len(public),
        "source_regions": sorted({r["source_region"] for r in public}),
        "processing_regions": sorted({r["processing_region"] for r in public if r["processing_region"]}),
        "teams": sorted({r["team"] for r in public}),
        "models": sorted({r["base_model"] for r in public}),
        "region_evidence": dict(Counter(r["region_evidence"] for r in public)),
        "cost_status": dict(Counter(r["cost_status"] for r in public)),
        "price_effective_dates": sorted({r["price_effective_date"] for r in public if r["price_effective_date"]}),
        "cost_label": "Estimated inference cost (USD)",
        "limitations": LIMITATIONS,
    }

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "requests.json").write_text(json.dumps(public, indent=1) + "\n")
    # All known regions: live demo requests may be processed in regions outside the dataset.
    (OUT / "regions.json").write_text(json.dumps(region_points, indent=1, ensure_ascii=False) + "\n")
    (OUT / "meta.json").write_text(json.dumps(meta, indent=1) + "\n")
    print(f"{len(public)} requests, {len(used)} regions used -> {OUT.relative_to(ROOT)}")
    print("identities:", sorted(set(sessions.values())))


if __name__ == "__main__":
    main()
